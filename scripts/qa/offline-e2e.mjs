await context.route('**/*', async route => {
  const url=new URL(route.request().url());
  if (url.hostname === '127.0.0.1' || url.hostname === 'localhost') return route.continue();
  if (url.origin !== 'https://backendmarketplacemoda-production.up.railway.app') return route.abort('blockedbyclient');
  if (offline) return route.abort('internetdisconnected');
  const response=await route.fetch({url:'http://127.0.0.1:57519'+url.pathname+url.search});
  if(response.status()>=400 && !url.pathname.includes('refresh')) failures.push([url.pathname,response.status(),(await response.text()).slice(0,350)]);
  await route.fulfill({response,headers:{...response.headers(),'access-control-allow-origin':'http://127.0.0.1:57520','access-control-allow-credentials':'true'}});
});
